#1. and: If both operands are true then return true,
       #else return false
print(True and True) 
print(True and False)

#2. or: If both operands are false then return false,
       # else return true
print(True or False)
print(False or False)

#Falsy: False, None, 0, blank value like:" ", []
#e.g , print(" " or 10)

#3. not : opposite of operands 
print( not True)
print( not False)